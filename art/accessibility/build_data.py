def cr(a, b):
    return float(cvd.contrast(cvd.hex_to_rgb(a), cvd.hex_to_rgb(b)))


def shade(h, v_mul, s_mul, v_abs=None):
    r, g, b = cvd.hex_to_rgb(h)
    hh, s, v = colorsys.rgb_to_hsv(r, g, b)
    v = v_abs if v_abs is not None else v * v_mul
    return cvd.rgb_to_hex(colorsys.hsv_to_rgb(hh, min(1.0, s * s_mul), v))


def lift_for_contrast(h, bg, target):
    """Mix toward white until `h` reaches `target`:1 against `bg` (unchanged if it already does)."""
    c = cvd.hex_to_rgb(h)
    for k in range(0, 101):
        m = c + (1.0 - c) * (k / 100.0)
        if cr(cvd.rgb_to_hex(m), bg) >= target:
            return cvd.rgb_to_hex(m)
    return "#ffffff"


def set_entry(sid, colors, analysis):
    s = analysis["summary"]
    return {
        "id": sid,
        "names": NAMES[sid],
        "colors": colors,
        # Darker shade (cassette shell shading, inactive fills) and near-black tint (lane / deck
        # backgrounds): the same roles as UiPalette.TAPE_DEEP / TAPE_NIGHT.
        "deep": [shade(c, 0.70, 1.08) for c in colors],
        "night": [shade(c, 1.0, 0.62, v_abs=0.22) for c in colors],
        # Text / icon colour to draw ON a fill of the cassette colour (whichever of ink and paper
        # contrasts more), and the cassette colour lifted until it reads as TEXT on the HUD panel.
        "on_color": [INK if cr(c, INK) >= cr(c, PAPER) else PAPER for c in colors],
        "on_color_contrast": [round(max(cr(c, INK), cr(c, PAPER)), 2) for c in colors],
        "text_on_panel": [lift_for_contrast(c, refs.HUD["panel"], 4.5) for c in colors],
        "metrics": {
            "pairwise_dE2000": analysis["pairwise"],
            "worst_pair": s["worst_pair"],
            "nearest_reserved": s["nearest_reserved"],
            "nearest_theme_accent": s["nearest_accent"],
            "worst_floor_contrast": s["worst_floor_contrast"],
            "worst_floor_dE_any_vision": s["worst_floor_dE_any_vision"],
            "contrast_on_hud_panel": analysis["hud"]["panel"]["contrast"],
            "contrast_with_ink": analysis["hud"]["ink"]["contrast"],
        },
    }


